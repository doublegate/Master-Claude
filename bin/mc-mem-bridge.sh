#!/bin/sh
# mc-mem-bridge.sh — make the shared memory-core facts available to Codex and Antigravity.
# Builds one consolidated digest from memory-core/ and writes it as `master-memory.md` into
# each agent's global config directory, so they can use the same curated facts Claude gets:
#   codex        ~/.codex                 (Codex CLI; the default target)
#   antigravity  ~/.gemini/config         (Antigravity CLI `agy`; only with --only agy)
#   gemini       ~/.gemini                (legacy Gemini CLI, deprecated; only with --only gemini)
# For Antigravity prefer bin/mc-agy.sh: it embeds this digest together with the core in the
# master-claude agy plugin, because agy does not follow @imports or read files on its own.
# DRY-RUN by default; pass --execute to write. Idempotent (regenerates the digest).
# --stdout prints only the digest (used by mc-agy.sh) and writes nothing.
#
# Usage: mc-mem-bridge.sh [--execute | --stdout] [--only codex|antigravity|agy|gemini]
#                         [--codex-home DIR] [--agy-home DIR] [--gemini-home DIR]
set -eu

SCRIPT_DIR=$(CDPATH='' cd -- "$(dirname -- "$0")" && pwd)
REPO_ROOT=$(CDPATH='' cd -- "$SCRIPT_DIR/.." && pwd)
MEMCORE="$REPO_ROOT/memory-core"

EXECUTE=0
STDOUT=0
CODEX_HOME="$HOME/.codex"
AGY_HOME="$HOME/.gemini/config"
GEMINI_HOME="$HOME/.gemini"
ONLY=""

need() { [ "$1" -gt 1 ] || { printf 'mc-mem-bridge: %s requires an argument\n' "$2" >&2; exit 1; }; }

while [ $# -gt 0 ]; do
  case "$1" in
    --execute) EXECUTE=1; shift ;;
    --stdout) STDOUT=1; shift ;;
    --codex-home) need $# "$1"; CODEX_HOME="$2"; shift 2 ;;
    --agy-home|--antigravity-home) need $# "$1"; AGY_HOME="$2"; shift 2 ;;
    --gemini-home) need $# "$1"; GEMINI_HOME="$2"; shift 2 ;;
    --only) need $# "$1"; ONLY="$2"; shift 2 ;;
    -h|--help) sed -n '2,14p' "$0"; exit 0 ;;
    *) printf 'mc-mem-bridge: unknown arg: %s\n' "$1" >&2; exit 1 ;;
  esac
done
[ -d "$MEMCORE" ] || { printf 'mc-mem-bridge: no memory-core at %s\n' "$MEMCORE" >&2; exit 1; }

strip_fm() { awk 'NR==1 && $0=="---"{fm=1;next} fm==1 && $0=="---"{fm=0;next} fm!=1{print}' "$1"; }

DIGEST=$(mktemp); trap 'rm -f "$DIGEST"' EXIT
{
  printf '# Master-Claude — shared memory digest\n\n'
  printf '%s\n\n' "> Generated by mc-mem-bridge from memory-core/. Curated, cross-project facts so"
  printf '%s\n\n' "> Codex and Antigravity share what Claude knows. Point your global agent config at"
  printf '%s\n\n' "> this file (Codex AGENTS.md / Antigravity GEMINI.md), or paste the relevant entries in."
  for f in "$MEMCORE"/*.md; do
    [ -e "$f" ] || continue
    b=$(basename -- "$f"); [ "$b" = MEMORY.md ] && continue
    name=$(sed -n 's/^name:[[:space:]]*//p' "$f" | head -n 1)
    [ -n "$name" ] || name=$(basename -- "$f" .md)
    printf '## %s\n\n' "$name"
    strip_fm "$f" | sed '/^[[:space:]]*$/{N;/^[[:space:]]*\n[[:space:]]*$/D}'
    printf '\n'
  done
} > "$DIGEST"

if [ "$STDOUT" -eq 1 ]; then cat "$DIGEST"; exit 0; fi

facts=0
for f in "$MEMCORE"/*.md; do
  [ -e "$f" ] || continue
  [ "${f##*/}" = MEMORY.md ] && continue
  facts=$((facts+1))
done
lines=$(wc -l < "$DIGEST" | tr -d ' ')

mode="DRY-RUN (no files written; pass --execute)"
[ "$EXECUTE" -eq 1 ] && mode="EXECUTE"
printf 'mc-mem-bridge: %s — %s facts -> %s-line digest\n' "$mode" "$facts" "$lines"

WROTE=""
write_one() {
  label="$1"; home="$2"
  dest="$home/master-memory.md"
  if [ "$EXECUTE" -eq 1 ]; then
    mkdir -p "$home"
    cp "$DIGEST" "$dest"
    printf '  wrote %s (%s)\n' "$dest" "$label"
  else
    printf '  would write %s (%s)\n' "$dest" "$label"
  fi
  WROTE="$WROTE $label"
}

case "$ONLY" in
  codex)           write_one codex "$CODEX_HOME" ;;
  antigravity|agy) write_one antigravity "$AGY_HOME" ;;
  gemini)          write_one gemini "$GEMINI_HOME" ;;
  "")              write_one codex "$CODEX_HOME" ;;
  *) printf 'mc-mem-bridge: --only must be codex|antigravity|agy|gemini\n' >&2; exit 1 ;;
esac

printf 'Then reference it from each global config (once):\n'
case "$WROTE" in *codex*)
  printf '  Codex       %s/AGENTS.md: "See master-memory.md in this directory for shared conventions."\n' "$CODEX_HOME" ;;
esac
case "$WROTE" in *antigravity*)
  printf '  Antigravity %s/GEMINI.md: "At session start, read %s/master-memory.md for shared conventions."\n' "$AGY_HOME" "$AGY_HOME"
  printf '              (agy does not expand @imports, so name the file for the agent to read)\n' ;;
esac
case "$WROTE" in *gemini*)
  printf '  Gemini CLI  %s/GEMINI.md (deprecated): "@./master-memory.md"\n' "$GEMINI_HOME" ;;
esac
[ "$EXECUTE" -eq 1 ] || printf 'Re-run with --execute to write.\n'
